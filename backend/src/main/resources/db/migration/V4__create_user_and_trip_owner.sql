-- Accounts, and the owner of each trip. Trips become private to their owner.
-- The database starts empty (no seeded trips), so owner_id can be NOT NULL at once.

CREATE TABLE app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    email         VARCHAR(254)                NOT NULL,
    password_hash VARCHAR(100)                NOT NULL,
    display_name  VARCHAR(50)                 NOT NULL,
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_app_user PRIMARY KEY (id),
    CONSTRAINT uq_app_user_email UNIQUE (email)
);

ALTER TABLE trip ADD COLUMN owner_id BIGINT NOT NULL;
ALTER TABLE trip ADD CONSTRAINT fk_trip_owner FOREIGN KEY (owner_id) REFERENCES app_user (id);
CREATE INDEX ix_trip_owner ON trip (owner_id);
