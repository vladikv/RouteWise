-- Multi-stop trips: a trip is an ordered list of 2-10 stops instead of origin/destination.
-- Every existing trip becomes two stops (origin at position 0, destination at 1),
-- then the old columns and their constraints are dropped.

CREATE TABLE trip_stop (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    trip_id       BIGINT  NOT NULL,
    city_id       BIGINT  NOT NULL,
    stop_position INTEGER NOT NULL,
    CONSTRAINT pk_trip_stop PRIMARY KEY (id),
    CONSTRAINT fk_trip_stop_trip FOREIGN KEY (trip_id) REFERENCES trip (id) ON DELETE CASCADE,
    CONSTRAINT fk_trip_stop_city FOREIGN KEY (city_id) REFERENCES city (id),
    CONSTRAINT uq_trip_stop_position UNIQUE (trip_id, stop_position),
    CONSTRAINT ck_trip_stop_position CHECK (stop_position BETWEEN 0 AND 9)
);

INSERT INTO trip_stop (trip_id, city_id, stop_position)
SELECT id, origin_city_id, 0 FROM trip;

INSERT INTO trip_stop (trip_id, city_id, stop_position)
SELECT id, destination_city_id, 1 FROM trip;

ALTER TABLE trip DROP CONSTRAINT ck_trip_distinct_cities;
ALTER TABLE trip DROP CONSTRAINT fk_trip_origin_city;
ALTER TABLE trip DROP CONSTRAINT fk_trip_destination_city;
ALTER TABLE trip DROP COLUMN origin_city_id;
ALTER TABLE trip DROP COLUMN destination_city_id;
