-- Regional pricing (feat/regional-pricing): reference data for cost estimates. Seeded in V13.
--
-- country_pricing: one row per country that has seeded cities. The car cost uses the fuel price and the
-- average toll per km; region picks the public transport fares below.
-- regional_fare: average fares per region for the modes sold as tickets (base fare + price per km,
-- per traveler). Modes or countries without a row fall back to transport_mode.cost_per_km.

CREATE TABLE country_pricing (
    country            VARCHAR(2)    NOT NULL,
    region             VARCHAR(20)   NOT NULL,
    fuel_eur_per_litre NUMERIC(5, 3) NOT NULL,
    toll_eur_per_km    NUMERIC(5, 3) NOT NULL,
    CONSTRAINT pk_country_pricing PRIMARY KEY (country),
    CONSTRAINT ck_country_pricing_fuel CHECK (fuel_eur_per_litre > 0),
    CONSTRAINT ck_country_pricing_toll CHECK (toll_eur_per_km >= 0)
);

CREATE TABLE regional_fare (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    region        VARCHAR(20)   NOT NULL,
    mode_code     VARCHAR(10)   NOT NULL,
    base_fare_eur NUMERIC(6, 2) NOT NULL,
    cost_per_km   NUMERIC(6, 3) NOT NULL,
    CONSTRAINT pk_regional_fare PRIMARY KEY (id),
    CONSTRAINT uq_regional_fare_region_mode UNIQUE (region, mode_code),
    CONSTRAINT fk_regional_fare_mode FOREIGN KEY (mode_code) REFERENCES transport_mode (code),
    CONSTRAINT ck_regional_fare_mode CHECK (mode_code IN ('TRAIN', 'BUS', 'PLANE')),
    CONSTRAINT ck_regional_fare_base CHECK (base_fare_eur >= 0),
    CONSTRAINT ck_regional_fare_cost CHECK (cost_per_km >= 0)
);
