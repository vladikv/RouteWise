CREATE TABLE trip (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    title               VARCHAR(100)             NOT NULL,
    origin_city_id      BIGINT                   NOT NULL,
    destination_city_id BIGINT                   NOT NULL,
    departure_date      DATE                     NOT NULL,
    travelers           INTEGER                  NOT NULL,
    priority            VARCHAR(10)              NOT NULL,
    notes               VARCHAR(1000),
    created_at          TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at          TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_trip PRIMARY KEY (id),
    CONSTRAINT fk_trip_origin_city FOREIGN KEY (origin_city_id) REFERENCES city (id),
    CONSTRAINT fk_trip_destination_city FOREIGN KEY (destination_city_id) REFERENCES city (id),
    CONSTRAINT ck_trip_distinct_cities CHECK (origin_city_id <> destination_city_id),
    CONSTRAINT ck_trip_travelers CHECK (travelers BETWEEN 1 AND 9),
    CONSTRAINT ck_trip_priority CHECK (priority IN ('FASTEST', 'CHEAPEST', 'GREENEST', 'BALANCED'))
);

CREATE INDEX ix_trip_departure_date ON trip (departure_date);
