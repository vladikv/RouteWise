CREATE TABLE city (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name      VARCHAR(100)     NOT NULL,
    country   VARCHAR(2)       NOT NULL,
    latitude  DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,
    CONSTRAINT pk_city PRIMARY KEY (id),
    CONSTRAINT uq_city_name_country UNIQUE (name, country),
    CONSTRAINT ck_city_latitude CHECK (latitude BETWEEN -90 AND 90),
    CONSTRAINT ck_city_longitude CHECK (longitude BETWEEN -180 AND 180)
);

CREATE TABLE transport_mode (
    code                   VARCHAR(10)   NOT NULL,
    avg_speed_kmh          INTEGER       NOT NULL,
    cost_per_km            NUMERIC(6, 3) NOT NULL,
    co2_grams_per_km       INTEGER       NOT NULL,
    fixed_overhead_minutes INTEGER       NOT NULL,
    max_distance_km        INTEGER       NOT NULL,
    CONSTRAINT pk_transport_mode PRIMARY KEY (code),
    CONSTRAINT ck_transport_mode_code CHECK (code IN ('TRAIN', 'BUS', 'CAR', 'BIKE', 'PLANE')),
    CONSTRAINT ck_transport_mode_speed CHECK (avg_speed_kmh > 0),
    CONSTRAINT ck_transport_mode_cost CHECK (cost_per_km >= 0),
    CONSTRAINT ck_transport_mode_co2 CHECK (co2_grams_per_km >= 0),
    CONSTRAINT ck_transport_mode_overhead CHECK (fixed_overhead_minutes >= 0),
    CONSTRAINT ck_transport_mode_max_distance CHECK (max_distance_km > 0)
);
